package samples.comparison.spring.order;

import jakarta.annotation.PostConstruct;
import java.util.List;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

@Repository
public class JdbcOrderRepository implements OrderRepository {
    private final JdbcTemplate jdbcTemplate;
    private final String seedProduct;

    public JdbcOrderRepository(
        JdbcTemplate jdbcTemplate,
        @Value("${comparison.order.seed-product:starter-kit}") String seedProduct
    ) {
        this.jdbcTemplate = jdbcTemplate;
        this.seedProduct = seedProduct;
    }

    @PostConstruct
    void initialize() {
        jdbcTemplate.update(
            """
            create table if not exists orders (
                id bigint generated by default as identity primary key,
                product varchar(255) not null,
                quantity integer not null,
                status varchar(64) not null
            )
            """
        );
        jdbcTemplate.update("delete from orders");
        save(seedProduct, 1, "SEEDED");
    }

    @Override
    public Order save(String product, int quantity, String status) {
        jdbcTemplate.update("insert into orders(product, quantity, status) values (?, ?, ?)", product, quantity, status);
        return jdbcTemplate.queryForObject(
            "select id, product, quantity, status from orders order by id desc fetch first 1 rows only",
            (resultSet, rowNum) -> new Order(
                resultSet.getLong("id"),
                resultSet.getString("product"),
                resultSet.getInt("quantity"),
                resultSet.getString("status")
            )
        );
    }

    @Override
    public List<Order> findAll() {
        return jdbcTemplate.query(
            "select id, product, quantity, status from orders order by id",
            (resultSet, rowNum) -> new Order(
                resultSet.getLong("id"),
                resultSet.getString("product"),
                resultSet.getInt("quantity"),
                resultSet.getString("status")
            )
        );
    }

    @Override
    public long count() {
        Long value = jdbcTemplate.queryForObject("select count(*) from orders", Long.class);
        return value == null ? 0 : value;
    }
}
